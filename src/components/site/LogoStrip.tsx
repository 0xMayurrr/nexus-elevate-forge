export function LogoStrip({ variant = "light" }: { variant?: "light" | "dark" }) {
  const isDark = variant === "dark";
  
  // Duplicate logos 3 times to ensure a seamless infinite scroll across any screen width
  const scrollItems = [...LOGOS, ...LOGOS, ...LOGOS, ...LOGOS];

  return (
    <div
      className={
        isDark
          ? "border-y border-white/10 bg-[color:var(--navy-deep)] py-8 md:py-10 overflow-hidden"
          : "border-y border-[color:var(--hairline)] bg-[color:var(--cream)] py-8 md:py-10 overflow-hidden"
      }
    >
      <div className="container-wide">
        <p
          className={
            isDark
              ? "eyebrow-light text-center w-full block mb-6 md:mb-8"
              : "eyebrow text-center w-full block mb-6 md:mb-8"
          }
        >
          Trusted by ambitious enterprises worldwide
        </p>
      </div>
      
      {/* Marquee Wrapper */}
      <div className="relative w-full overflow-hidden flex whitespace-nowrap">
        <div className="flex w-max animate-marquee hover:[animation-play-state:paused]">
          {scrollItems.map((item, idx) => {
            const Icon = item.Icon;
            return (
              <div
                key={`${item.name}-${idx}`}
                className={`flex items-center gap-3 px-8 md:px-14 font-display text-[1rem] md:text-[1.25rem] font-bold tracking-[0.1em] transition-opacity ${
                  isDark ? "text-[color:var(--cream)]" : "text-[color:var(--slate-ink)]"
                }`}
              >
                <Icon />
                {item.name}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}
